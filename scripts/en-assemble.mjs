// Builds scripts/english-extra.txt (read by build-data.mjs) from the themed word pools in scripts/en-extra/*.txt.
// Pool format:  @level|theme title|description|Icon   followed by   word|nghĩa|example|nghĩa câu ví dụ
// Words already in the course (after folding case, spaces, hyphens and plural endings) are dropped,
// each theme is cut into lessons of 12–14 words, and every 10 lessons of a level form one part.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { existing, key, pool } from './en-filter.mjs';

const dir = path.dirname(fileURLToPath(import.meta.url));
const seen = existing();
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9' ]/g, ' ').replace(/\s+/g, ' ').trim();
const levels = new Map();
const spare = new Map();
let dropped = 0;
const cut = (t, words) => {
  const k = Math.floor(words.length / 12);
  const lessons = levels.get(t.level) ?? [];
  levels.set(t.level, lessons);
  for (let i = 0, at = 0; i < k; i++) {
    const size = Math.floor(words.length / k) + (i < words.length % k ? 1 : 0);
    lessons.push({ ...t, title: k > 1 ? `${t.title} ${i + 1}` : t.title, words: words.slice(at, at + size) });
    at += size;
  }
};
const problems = [];
for (const t of pool()) {
  const words = [];
  for (const w of t.words) {
    const [word, vi, ex, exVi] = w.line.split('|');
    if (!exVi || !/[.?!]$/.test(ex) || !` ${norm(ex)} `.includes(` ${norm(word)} `)) {
      problems.push(`${w.where}: bad line (${word})`);
      continue;
    }
    if (seen.has(key(word))) {
      console.warn(`${w.where}: "${word}" is already in the course, dropped`);
      dropped++;
      continue;
    }
    seen.add(key(word));
    words.push(w.line);
  }
  const k = Math.floor(words.length / 12);
  if (!k) {
    problems.push(`${t.where}: theme "${t.title}" has only ${words.length} new words`);
    continue;
  }
  // Words beyond 14 per lesson move to the mixed lessons at the end of the level.
  if (words.length > 14 * k) spare.set(t.level, [...(spare.get(t.level) ?? []), ...words.splice(14 * k)]);
  cut(t, words);
}
for (const [level, words] of spare) {
  const k = Math.floor(words.length / 12);
  if (!k || words.length > 14 * k) {
    console.warn(`level ${level}: ${words.length} spare words do not fill whole lessons, ${words.length - 14 * k} dropped`);
    dropped += words.length - 14 * k;
    words.length = 14 * k;
  }
  if (k) cut({ level, title: 'Từ vựng tổng hợp', desc: 'Từ thuộc nhiều chủ đề', icon: 'Mix' }, words);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
const colors = ['leaf', 'sky', 'grape', 'coral', 'sun'];
const out = ['# Generated by scripts/en-assemble.mjs from scripts/en-extra/*.txt – do not edit by hand.', ''];
let total = 0;
for (const level of [...levels.keys()].sort()) {
  const lessons = levels.get(level);
  const parts = [];
  for (let i = 0; i < lessons.length; i += 10) parts.push(lessons.slice(i, i + 10));
  if (parts.length > 1 && parts.at(-1).length < 4) parts.at(-2).push(...parts.pop());
  parts.forEach((ls, p) => {
    const themes = [...new Set(ls.map((l) => l.title.replace(/\s+\d+$/, '')))];
    out.push(`%${level * 100 + 51 + p}|${level}|Phần ${p + 1}: Mở rộng – ${themes[0]}|${themes.slice(0, 5).join(', ')}|${colors[p % colors.length]}`);
    ls.forEach((l, i) => {
      out.push(`@y${level}${String(p * 20 + i + 1).padStart(3, '0')}|${l.title}|${l.desc}|${l.icon}`, ...l.words, '');
      total += l.words.length;
    });
  });
  console.log(`level ${level}: ${lessons.length} lessons, ${lessons.reduce((n, l) => n + l.words.length, 0)} words, ${parts.length} parts`);
}
fs.writeFileSync(path.join(dir, 'english-extra.txt'), out.join('\n'));
console.log(`english-extra.txt: ${total} words, ${dropped} dropped`);
